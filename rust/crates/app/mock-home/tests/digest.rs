//! The data's digest test. A fixed-seed set keeps its recorded digest, so a change to the bytes that `generate` writes
//! fails here until `DATA_VERSION` changes with it. Then record the new version and the new digest together.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use charliebot_mock_home::DATA_VERSION;
use charliebot_mock_home::generate::generate;
use sha2::{Digest, Sha256};

/// The data version that `RECORDED_DIGEST` and `SIZE_CURVE_DIGEST` belong to.
const RECORDED_VERSION: &str = "2";
/// The digest of a home of `SESSIONS` sessions generated with `SEED`.
const RECORDED_DIGEST: &str = "cfee41c00c363b0b3d87590c98870f7f9940ba15b499f67b1dc901760cc63775";
const SESSIONS: usize = 3;
const SEED: u64 = 7;
/// The digest of a home of `SIZE_CURVE_SESSIONS` sessions generated with `SEED`.
const SIZE_CURVE_DIGEST: &str = "7e4a3c903abb6db58a1b8eb32197569ca480df6a999ad93c7b3b58813b4d45ea";
/// Sessions sit at evenly spaced quantiles i / (n - 1), and the last size segment spans (0.99, 1]. At 102 sessions the
/// quantile 100 / 101 = 0.9901 falls inside it, so every segment of the size curve holds a session that is not a knot.
const SIZE_CURVE_SESSIONS: usize = 102;

/// The SHA-256 of every file's relative path and content hash, in path order.
fn digest_tree(root: &Path) -> String {
  let mut file_digests = BTreeMap::new();
  collect(root, root, &mut file_digests);
  let mut listing = Sha256::new();
  for (path, digest) in &file_digests {
    listing.update(format!("{path} {digest}\n"));
  }
  format!("{:x}", listing.finalize())
}

fn collect(root: &Path, dir: &Path, file_digests: &mut BTreeMap<String, String>) {
  for entry in fs::read_dir(dir).expect("a directory of the generated home") {
    let path = entry.expect("a directory entry").path();
    if path.is_dir() {
      collect(root, &path, file_digests);
    } else {
      let bytes = fs::read(&path).expect("a generated file");
      let relative = path.strip_prefix(root).expect("a path under the home").display().to_string();
      file_digests.insert(relative, format!("{:x}", Sha256::digest(&bytes)));
    }
  }
}

/// The digest of a home of `sessions` sessions generated with `seed`.
fn generated_digest(sessions: usize, seed: u64) -> String {
  let scratch = tempfile::tempdir().expect("a scratch directory");
  let output = scratch.path().join("home");
  generate(&output, sessions, seed).expect("the home generates");
  digest_tree(&output)
}

#[test]
fn a_fixed_seed_set_keeps_its_recorded_digest() {
  let digest = generated_digest(SESSIONS, SEED);
  assert_eq!(DATA_VERSION, RECORDED_VERSION, "DATA_VERSION changed without the recorded digest");
  assert_eq!(
    digest, RECORDED_DIGEST,
    "the generated bytes changed: bump DATA_VERSION, then record the new version and digest together"
  );
}

#[test]
fn a_size_curve_set_keeps_its_recorded_digest() {
  let digest = generated_digest(SIZE_CURVE_SESSIONS, SEED);
  assert_eq!(DATA_VERSION, RECORDED_VERSION, "DATA_VERSION changed without the recorded digest");
  assert_eq!(
    digest, SIZE_CURVE_DIGEST,
    "the generated bytes changed: bump DATA_VERSION, then record the new version and digest together"
  );
}
