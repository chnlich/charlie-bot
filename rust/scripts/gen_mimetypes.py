"""Print crates/infra/compat/src/mimetypes_table.rs from this interpreter's mimetypes defaults.

The Rust static-file server guesses content types the way CPython's mimetypes module does: these
built-in tables first, then the system mime.types files, read at startup. Regenerate the table with
the interpreter of the Python baseline when that baseline moves:

    uv run python rust/scripts/gen_mimetypes.py > rust/crates/infra/compat/src/mimetypes_table.rs
    (cd rust && cargo fmt)
"""

import mimetypes
import sys


def rust_str(text: str) -> str:
  return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def table(name: str, doc: str, pairs: dict[str, str]) -> str:
  rows = "\n".join(f"  ({rust_str(key)}, {rust_str(value)})," for key, value in pairs.items())
  return f"/// {doc}\npub const {name}: &[(&str, &str)] = &[\n{rows}\n];\n"


def main() -> None:
  version = ".".join(str(part) for part in sys.version_info[:3])
  print(f"//! CPython {version} `mimetypes` built-in tables, generated by rust/scripts/gen_mimetypes.py.")
  print()
  print(table("SUFFIX_MAP", "`_suffix_map_default`: suffixes that expand to two suffixes.", mimetypes._suffix_map_default))
  print(table("ENCODINGS_MAP", "`_encodings_map_default`: case-sensitive encoding suffixes.",
              mimetypes._encodings_map_default))
  print(table("TYPES_MAP", "`_types_map_default`: the strict extension -> type table, in insertion order.",
              mimetypes._types_map_default), end="")


if __name__ == "__main__":
  main()
