"""Print crates/infra/core/src/printable_table.rs: the code points that CPython's str.isprintable() rejects.

pyfmt::str_repr escapes every character that str.isprintable() rejects, as CPython's repr does. That set comes
from the Unicode database of the interpreter, so regenerate the table with the interpreter of the Python baseline
when that baseline moves:

    uv run python rust/scripts/gen_printable.py > rust/crates/infra/core/src/printable_table.rs
    (cd rust && cargo fmt)
"""

import sys
import unicodedata

MAX_CODE_POINT = 0x10FFFF


def non_printable_ranges() -> list[tuple[int, int]]:
  """The inclusive ranges of code points for which str.isprintable() is false, in ascending order."""
  ranges: list[tuple[int, int]] = []
  start: int | None = None
  for code_point in range(MAX_CODE_POINT + 1):
    if not chr(code_point).isprintable():
      if start is None:
        start = code_point
    elif start is not None:
      ranges.append((start, code_point - 1))
      start = None
  if start is not None:
    ranges.append((start, MAX_CODE_POINT))
  return ranges


def main() -> None:
  version = ".".join(str(part) for part in sys.version_info[:3])
  print(
      f"//! The code points that CPython {version} `str.isprintable()` rejects (Unicode "
      f"{unicodedata.unidata_version}), as inclusive ranges.")
  print("//! Generated by rust/scripts/gen_printable.py; `pyfmt::str_repr` escapes these code points.")
  print()
  print("/// The non-printable code points in ascending order. Each pair is an inclusive range.")
  print("pub const NON_PRINTABLE: &[(u32, u32)] = &[")
  for low, high in non_printable_ranges():
    print(f"  (0x{low:04x}, 0x{high:04x}),")
  print("];")


if __name__ == "__main__":
  main()
